<?php
// Подключаем файл конфигурации, где хранятся ключи API и координаты аэродрома
require_once __DIR__ . '/config.php';

// Главная функция для расчета "Летной годности" (виджета на главной странице)
function getFlightStatus() {
    // Используем глобальные переменные конфигурации
    global $openweathermap_api_key, $lat, $lon, $use_mock_data;

    // Начальные (дефолтные) параметры погоды
    $wind_speed = 0;   // Скорость ветра (м/с)
    $clouds = 0;       // Облачность (%)
    $visibility = 10000; // Видимость (в метрах)
    $weather_desc = 'ясно'; // Текстовое описание погоды

    // Если в настройках выключен демо-режим ($use_mock_data = false)
    if (!$use_mock_data) {
        // Формируем URL для запроса к API OpenWeatherMap
        $url = "https://api.openweathermap.org/data/2.5/weather?lat={$lat}&lon={$lon}&units=metric&lang=ru&appid={$openweathermap_api_key}";
        
        // Инициализируем cURL сессию для выполнения HTTP-запроса
        $ch = curl_init();
        curl_setopt($ch, CURLOPT_URL, $url);
        curl_setopt($ch, CURLOPT_RETURNTRANSFER, 1); // Вернуть ответ в виде строки вместо вывода на экран
        curl_setopt($ch, CURLOPT_TIMEOUT, 5); // Таймаут соединения 5 секунд
        
        // Выполняем запрос
        $response = curl_exec($ch);
        $http_code = curl_getinfo($ch, CURLINFO_HTTP_CODE); // Получаем HTTP статус-код ответа
        curl_close($ch); // Закрываем cURL сессию

        // Если запрос успешен (HTTP код 200) и мы получили ответ
        if ($http_code == 200 && $response) {
            // Декодируем JSON строку в ассоциативный массив PHP
            $data = json_decode($response, true);
            // Извлекаем нужные параметры погоды из массива данных
            if (isset($data['wind']['speed'])) $wind_speed = $data['wind']['speed'];
            if (isset($data['clouds']['all'])) $clouds = $data['clouds']['all'];
            if (isset($data['visibility'])) $visibility = $data['visibility'];
            if (isset($data['weather'][0]['description'])) $weather_desc = $data['weather'][0]['description'];
            
            // Получаем код погоды (ID) для точного анализа осадков (дождь, гроза и т.д.)
            $weather_id = isset($data['weather'][0]['id']) ? $data['weather'][0]['id'] : 800;
        } else {
            // Если API недоступно или произошла ошибка, принудительно включаем демо-данные
            $use_mock_data = true;
        }
    }

    // Если включен демо-режим (или API не сработало), генерируем случайные реалистичные данные
    if ($use_mock_data) {
        $wind_speed = rand(2, 6) + (rand(0, 9) / 10); // Ветер от 2.0 до 6.9 м/с
        $clouds = rand(10, 60); // Облачность от 10% до 60%
        $visibility = rand(8000, 10000); // Видимость от 8 до 10 км
        $weather_desc = 'переменная облачность (демо)';
        $weather_id = 800; // Код 800 означает "Ясно / Чистое небо"
    }

    // Алгоритм расчета баллов "Летной годности" (начинаем со 100 баллов и снижаем за плохую погоду)
    $score = 100;
    
    // 1. Анализ осадков (осадки - критический фактор для полетов и прыжков)
    // Коды OpenWeatherMap: < 700 означает грозы, дожди, снег
    if ($weather_id < 700) {
        $score -= 60; // Штраф за любые осадки
    } elseif ($weather_id >= 701 && $weather_id <= 781) {
        $score -= 40; // Штраф за туман, мглу, плохую видимость из-за взвеси
    }

    // 2. Анализ ветра (для парашютного спорта ветер > 7-8 м/с опасен для новичков)
    if ($wind_speed > 2) {
        // За каждый метр в секунду свыше 2 м/с отнимаем по 12 баллов
        $score -= ($wind_speed - 2) * 12; 
    }
    
    // 3. Анализ облачности (высокая облачность мешает визуальному ориентированию пилота и парашютиста)
    if ($clouds > 50) {
        // Отнимаем по 0.5 балла за каждый процент облачности выше 50%
        $score -= ($clouds - 50) * 0.5;
    }

    // 4. Анализ дальности видимости
    if ($visibility < 8000) {
        // Снижаем баллы, если видимость хуже 8 км
        $score -= (8000 - $visibility) / 100;
    }

    // Ограничиваем итоговый балл в пределах от 0 до 100
    $score = max(0, min(100, (int)$score));

    // Маппинг итогового балла на вердикт, цвета и угол поворота стрелки спидометра
    // Стрелка поворачивается от -90 градусов (0% годности) до +90 градусов (100% годности)
    if ($score >= 80) {
        $verdict = 'Идеальные условия! Подходит для новичков и профи.';
        $status_color = '#00ff88'; // Яркий зеленый
        $bg_color = 'rgba(0, 51, 27, 0.7)'; // Темно-зеленый фон плашки
        $angle = 60 + (($score - 80) / 20 * 30); // Угол стрелки от 60 до 90 градусов
        $tips = 'Совет: Не забудьте взять солнцезащитные очки и экшен-камеру для крутых кадров!';
    } elseif ($score >= 60) {
        $verdict = 'Хорошие условия. Возможны небольшие ограничения.';
        $status_color = '#ffd700'; // Золотой/Желтый
        $bg_color = 'rgba(51, 43, 0, 0.7)'; // Темно-желтый фон плашки
        $angle = 0 + (($score - 60) / 20 * 60); // Угол стрелки от 0 до 60 градусов
        if ($wind_speed > 4) {
            $tips = 'Совет: Ветер ощутимый. Слушайте инструктора внимательно при приземлении.';
        } else {
            $tips = 'Совет: Отличный день для прыжка в тандеме.';
        }
    } elseif ($score >= 40) {
        $verdict = 'Условия на грани. Только для спортсменов.';
        $status_color = '#ff9f43'; // Оранжевый
        $bg_color = 'rgba(51, 26, 0, 0.7)'; // Темно-оранжевый фон плашки
        $angle = -60 + (($score - 40) / 20 * 60); // Угол стрелки от -60 до 0 градусов
        $tips = 'Совет: Прыжки для перворазников могут быть перенесены. Уточните у администратора.';
    } else {
         $verdict = 'Полеты приостановлены по метеоусловиям.';
         $status_color = '#ff3333'; // Красный
         $bg_color = 'rgba(51, 0, 0, 0.7)'; // Темно-красный фон плашки
         $angle = -90 + (($score) / 40 * 30); // Угол стрелки от -90 до -60 градусов
         $tips = 'Совет: Безопасность превыше всего! Позвоните нам, чтобы перенести запись.';
    }

    // Возвращаем собранный массив с результатами расчета
    return [
        'score' => $score,
        'verdict' => $verdict,
        'tips' => $tips,
        'status_color' => $status_color,
        'bg_color' => $bg_color,
        'angle' => $angle,
        'wind' => round($wind_speed, 1),
        'clouds' => $clouds,
        'desc' => mb_ucfirst($weather_desc)
    ];
}

// Вспомогательная функция для перевода первой буквы строки в верхний регистр (поддерживает кириллицу UTF-8)
function mb_ucfirst($str) {
    if (empty($str)) return $str;
    $fc = mb_strtoupper(mb_substr($str, 0, 1));
    return $fc . mb_substr($str, 1);
}
